/// Escala de raio de borda do Design System — todo `BorderRadius` de tela
/// nova usa um destes valores.
abstract final class AppRadius {
  /// 8 — controles pequenos (botão, input, chip retangular).
  static const sm = 8.0;

  /// 10 — contêineres médios (ex.: círculo/quadrado de ícone).
  static const md = 10.0;

  /// 14 — cantos padrão dos Cards e painéis.
  static const lg = 14.0;

  /// Totalmente arredondado — pills, badges, avatares circulares.
  static const pill = 999.0;
}
